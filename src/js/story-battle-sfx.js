/* Story sound recipes (STORY-BATTLE-SFX + STORY-RECORDER).
 *
 * Synthesized cues for combat and boss effects, registered into game.js's ND_SFX_FALLBACK table. They play whenever a name
 * has no downloadable file (or the file has not loaded), so every on-screen effect always has a sound.
 * Tuning guide: tone(t,freq,dur,{type,to,gain}) is a pitched body, noise(t,dur,{type,freq,to,q,gain}) a filtered hiss.
 * Keep them low and dry; bright rising or chiming tones read as playful, which this fight should not be.
 * Load order: after game.js, before any battle starts. Matching visuals: story-battle-fx.js / story-battle-fx.css.
 */
(() => {
  'use strict';
  if (typeof ND_SFX_FALLBACK === 'undefined' || !ND_SFX_FALLBACK.recipes) return;
  // STORY-RECORDER: the recorder cues are shipped as audio files (assets/audio/story, generated by scripts/gen_recorder_sfx.py).
  // They join game.js's sound bank under the same names; the synthesized recipes below stay as the fallback while a file loads or fails.
  const FILES = { recorderOn: 'assets/audio/story/recorder-on.mp3', recorderPlay: 'assets/audio/story/recorder-play.mp3', recorderCut: 'assets/audio/story/recorder-cut.mp3', abyssRoar: 'assets/audio/story/abyss-roar.mp3' };
  // All user volume defaults are 10%; per-cue mix calibration stays in ND_MIX.
  const LEVELS = { recorderOn: .1, recorderPlay: .1, recorderCut: .1, abyssRoar: .1 };
  try {
    if (typeof AUDIO_URLS !== 'undefined') Object.assign(AUDIO_URLS, FILES);
    if (typeof AUDIO_DEFAULTS !== 'undefined') Object.assign(AUDIO_DEFAULTS, LEVELS);
    if (typeof AudioBank !== 'undefined' && Object.keys(AudioBank).length) {
      for (const [name, url] of Object.entries(FILES)) {
        if (AudioBank[name]) continue;
        const a = new Audio(); a.src = url; a.preload = 'auto'; a.volume = typeof getAudioVolume === 'function' ? getAudioVolume(name) : LEVELS[name]; AudioBank[name] = a; a.load();
      }
    }
  } catch (e) { console.warn('recorder audio files not registered', e); }
  Object.assign(ND_SFX_FALLBACK.recipes, {
      shield(t){this.tone(t,170,.22,{type:'sine',to:110,gain:.34});this.noise(t,.14,{freq:1100,to:600,q:1.6,gain:.3});this.noise(t+.02,.06,{type:'highpass',freq:2600,gain:.12});},
      lock(t){this.noise(t,.06,{type:'highpass',freq:2200,gain:.3});this.tone(t,240,.18,{type:'sine',to:130,gain:.36});this.noise(t+.07,.1,{freq:700,q:1.4,gain:.22});},
      burn(t){this.noise(t,.5,{type:'lowpass',freq:700,to:2000,gain:.3});for(let i=0;i<3;i++)this.noise(t+.06+i*.13,.05,{freq:1800,q:1.2,gain:.12});},
      evade(t){this.noise(t,.24,{freq:500,to:2200,q:1.1,gain:.3});this.tone(t,140,.18,{type:'sine',to:70,gain:.14});},
      devour(t){this.tone(t,120,.24,{type:'sine',to:55,gain:.5});this.noise(t,.2,{type:'lowpass',freq:800,to:260,gain:.4});this.noise(t+.16,.12,{type:'lowpass',freq:500,gain:.3});this.tone(t+.2,80,.2,{type:'sine',to:50,gain:.3});},
      grab(t){this.noise(t,.1,{freq:700,to:350,q:1.2,gain:.3});this.tone(t,130,.14,{type:'sine',to:80,gain:.3});this.noise(t+.05,.07,{type:'highpass',freq:2200,gain:.14});},
      swing(t){this.noise(t,.17,{freq:450,to:1900,q:.9,gain:.3});this.tone(t+.05,110,.1,{type:'sine',to:70,gain:.16});},
      gunshot(t){this.noise(t,.07,{type:'highpass',freq:1400,to:3500,gain:.4});this.tone(t,95,.2,{type:'sine',to:40,gain:.55});this.noise(t+.03,.22,{type:'lowpass',freq:1100,to:250,gain:.3});},
      skillCast(t){this.noise(t,.32,{freq:260,to:1100,q:.9,gain:.26});this.tone(t,95,.34,{type:'sine',to:140,gain:.3});},
      crit(t){this.tone(t,85,.22,{type:'sine',to:42,gain:.6});this.noise(t,.06,{type:'highpass',freq:2800,gain:.3});this.noise(t+.02,.16,{type:'lowpass',freq:1400,to:400,gain:.3});},
      energy(t){this.noise(t,.05,{freq:900,q:1.5,gain:.16});this.tone(t,190,.14,{type:'sine',to:150,gain:.14});},
      unitDown(t){this.tone(t,150,.5,{type:'sine',to:40,gain:.5});this.noise(t,.34,{type:'lowpass',freq:1000,to:180,gain:.36});this.noise(t+.04,.14,{type:'highpass',freq:2400,gain:.14});},
      explode(t){this.tone(t,120,.45,{type:'sine',to:35,gain:.7});this.noise(t,.4,{type:'lowpass',freq:2800,to:240,gain:.6});this.noise(t,.12,{type:'highpass',freq:3500,gain:.3});},
      turnStart(t){this.tone(t,105,.14,{type:'sine',to:80,gain:.12});},
      counter(t){this.tone(t,150,.16,{type:'sine',to:80,gain:.32});this.noise(t,.1,{freq:1200,q:1.2,gain:.28});},
      transformCharge(t){this.tone(t,60,.85,{type:'sine',to:160,gain:.4});this.noise(t,.85,{type:'lowpass',freq:240,to:1400,gain:.4});this.noise(t+.2,.6,{freq:500,to:1300,q:.8,gain:.12});},
      transformBurst(t){this.tone(t,120,1,{type:'sine',to:34,gain:.8});this.noise(t,.9,{type:'lowpass',freq:2200,to:160,gain:.55});this.noise(t,.1,{type:'highpass',freq:2600,gain:.28});[90,135].forEach(f=>this.tone(t,f,.9,{type:'sine',to:f/2,gain:.2}));},
      summon(t){this.noise(t,.42,{freq:250,to:1200,q:1,gain:.28});this.tone(t,90,.32,{type:'sine',to:130,gain:.26});this.noise(t+.2,.14,{type:'highpass',freq:2000,gain:.1});},
      purge(t){this.tone(t,95,.32,{type:'sine',to:42,gain:.6});this.noise(t,.22,{type:'lowpass',freq:1600,to:280,gain:.4});},
      buff(t){this.noise(t,.34,{freq:300,to:750,q:.8,gain:.22});this.tone(t,120,.34,{type:'sine',to:170,gain:.22});},
      shadow(t){this.noise(t,.3,{freq:420,to:1700,q:1,gain:.28});this.tone(t,100,.32,{type:'sine',to:60,gain:.24});},
      victory(t){[130.8,196,261.6].forEach((f,i)=>this.tone(t+i*.2,f,.9,{type:'sine',gain:.2}));},
      defeat(t){
        // a low, slow funeral toll: dull impact, then a falling minor line that sinks into silence
        this.tone(t,70,.9,{type:'sine',to:44,gain:.4});
        this.noise(t,.5,{type:'lowpass',freq:420,to:140,gain:.2});
        [[146.8,0],[130.8,.62],[116.5,1.24],[98,1.9]].forEach(([f,d],i)=>{
          this.tone(t+d,f,1.1+i*.12,{type:'sine',gain:.24-i*.02});
          this.tone(t+d,f/2,1.2+i*.12,{type:'sine',gain:.16});
        });
      },
      // STORY-RECORDER: the repaired crystal recorder. Power-up on assembly, a tape click + hiss under every recorded line,
      // and a burst of static when the recording cuts out.
      // STORY-ROAR: synth fallback if assets/audio/story/abyss-roar.mp3 cannot load. A low, ragged growl with a bright crystal rattle.
      // H2-RESONANCE: H2-r20 reuses the game's own resonance sounds (fxResFire then fxResImpact, from story-skill-sfx.js).
      // H2 cues reuse the game's existing sounds (coinFlip, fxRes*, fxQuakeCrack, fxUnityStrike) — see STEP_CUES in story-campaign.js.
      abyssRoar(t){
        this.tone(t,70,.9,{type:'sawtooth',to:95,gain:.3});
        this.tone(t+.9,95,1.4,{type:'sawtooth',to:60,gain:.26});
        this.noise(t,2.2,{freq:700,to:380,q:1.1,gain:.3});
        this.noise(t+.05,1.6,{freq:4800,to:3000,q:2,gain:.1});
      },
      recorderOn(t){
        this.noise(t,.05,{type:'highpass',freq:2200,gain:.3});
        this.tone(t+.06,90,.55,{type:'sine',to:190,gain:.2});
        this.noise(t+.06,.55,{type:'lowpass',freq:700,to:1500,gain:.14});
        this.tone(t+.5,140,.09,{type:'sine',to:70,gain:.32});
        this.noise(t+.5,.06,{type:'highpass',freq:2000,gain:.25});
        this.noise(t+.58,.5,{freq:3400,q:.7,gain:.08});
        [.7,.82,.93].forEach(d=>this.noise(t+d,.02,{type:'highpass',freq:4200,gain:.14}));
      },
      recorderPlay(t){
        this.noise(t,.04,{type:'highpass',freq:2500,gain:.24});
        this.tone(t,120,.5,{type:'sine',gain:.05});
        this.noise(t+.04,.55,{freq:3200,q:.7,gain:.08});
        [.12,.24,.33].forEach(d=>this.noise(t+d,.02,{type:'highpass',freq:4000,gain:.13}));
      },
      recorderCut(t){
        this.noise(t,.55,{freq:2600,to:900,q:.5,gain:.34});
        this.noise(t,.12,{type:'highpass',freq:3000,gain:.3});
        [.08,.17,.26,.36].forEach(d=>this.noise(t+d,.025,{type:'highpass',freq:4200,gain:.18}));
        this.tone(t+.5,110,.14,{type:'sine',to:60,gain:.32});
        this.noise(t+.5,.05,{type:'highpass',freq:2000,gain:.25});
      }
  });
})();
